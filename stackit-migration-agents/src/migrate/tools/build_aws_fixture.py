"""Build `fixtures/aws/inventory.json` from recorded AWS API responses.

The mock inventory is not hand-written: recorded API responses
(`fixtures/aws/raw/recorded-responses.json`) are replayed through the real
`AwsAdapter` with botocore's Stubber, so mock mode exercises the same
normalisation code as a live run. A test re-runs this and compares.

    uv run python -m migrate.tools.build_aws_fixture
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import boto3
from botocore.stub import Stubber

from migrate.adapters.aws import AwsAdapter
from migrate.adapters.base import INVENTORY_SECTIONS
from migrate.config import PROJECT_ROOT

RAW = PROJECT_ROOT / "fixtures" / "aws" / "raw" / "recorded-responses.json"
OUT = PROJECT_ROOT / "fixtures" / "aws" / "inventory.json"


def stubbed_adapter(raw: dict[str, Any]) -> tuple[AwsAdapter, list[Stubber]]:
    session = boto3.Session(
        aws_access_key_id="AKIDEXAMPLE",
        aws_secret_access_key="example",  # noqa: S106 - fake creds for Stubber
        region_name=raw["region"],
    )
    adapter = AwsAdapter(region=raw["region"], session=session)
    stubbers = []
    for service in ("sts", "ec2", "rds", "s3", "cloudwatch", "elbv2", "eks"):
        stubber = Stubber(adapter.client(service))
        for call in raw.get(service, []):
            if "error" in call:
                stubber.add_client_error(
                    call["method"],
                    service_error_code=call["error"],
                    http_status_code=404,
                )
            else:
                stubber.add_response(call["method"], call["response"])
        stubber.activate()
        stubbers.append(stubber)
    return adapter, stubbers


def build(raw_path: Path = RAW) -> dict[str, Any]:
    raw = json.loads(raw_path.read_text(encoding="utf-8"))
    adapter, stubbers = stubbed_adapter(raw)
    inventory = {
        "_note": "Generated by migrate.tools.build_aws_fixture from recorded responses. Do not edit by hand.",
        "cloud": "aws",
        "account_id": adapter.account_id(),
        "region": adapter.region,
        "sections": {
            name: [r.model_dump(mode="json") for r in getattr(adapter, name)()]
            for name in INVENTORY_SECTIONS
        },
    }
    for stubber in stubbers:
        stubber.assert_no_pending_responses()
    return inventory


def main() -> None:
    inventory = build()
    OUT.write_text(json.dumps(inventory, indent=2) + "\n", encoding="utf-8")
    total = sum(len(v) for v in inventory["sections"].values())
    print(f"wrote {OUT.relative_to(PROJECT_ROOT)} ({total} resources)", file=sys.stderr)


if __name__ == "__main__":
    main()
